// The Event Guide's share of the tools' common package (packages/ad-tape), written into vendor/ before
// every test and build (and by `npm run vendor`): vendor/tape.js, the tape geometry bundled with what it
// reads; vendor/ad-tokens.json, the shared tokens; vendor/ad-tokens.css, the same tokens as --ad-* custom
// properties, which styles.css reads. vendor/ is generated, never committed: until 19 Oct 2026 these
// came from the separate Tape Type repository through a sync script.
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const tool = fileURLToPath(new URL("../", import.meta.url));
const pkg = fileURLToPath(new URL("../../../packages/ad-tape/src/", import.meta.url));
const vendor = (file) => `${tool}vendor/${file}`;
mkdirSync(`${tool}vendor`, { recursive: true });

execFileSync(fileURLToPath(new URL("../../../node_modules/.bin/esbuild", import.meta.url)), [
  `${pkg}../entry.ts`,
  "--bundle",
  "--format=esm",
  "--target=es2020",
  "--legal-comments=none",
  "--banner:js=// Generated by scripts/vendor.mjs from packages/ad-tape (geometry.ts, settings.ts). Do not edit by hand.",
  `--outfile=${vendor("tape.js")}`,
], { stdio: "inherit" });

const text = readFileSync(`${pkg}ad-tokens.json`, "utf8");
writeFileSync(vendor("ad-tokens.json"), text);
const tokens = JSON.parse(text);
const lines = [];
const add = (name, value) => lines.push(`  --ad-${name}: ${value};`);
lines.push("  /* Colours */");
for (const token of tokens.color.tokens) add(token.name, typeof token.value === "string" ? token.value : Object.values(token.value)[0]);
lines.push("  /* Type styles: size, line height, tracking, and weight on Barlow GX's own scale */");
for (const group of tokens.type.groups) {
  for (const style of group.styles) {
    add(`${style.name}-size`, style.fontSize);
    add(`${style.name}-line-height`, style.lineHeight);
    if (style.letterSpacing !== undefined) add(`${style.name}-letter-spacing`, style.letterSpacing);
    add(`${style.name}-weight`, style.fontWeight);
  }
}
for (const [family, label] of [["spacing", "Space"], ["size", "Sizes"], ["opacity", "Opacity"]]) {
  lines.push(`  /* ${label} */`);
  for (const token of tokens[family].tokens) add(token.name, token.value);
}
lines.push("  /* The chrome every tool shares (ui) */");
for (const token of tokens.ui.tokens) add(`ui-${token.name}`, token.value);
lines.push("  /* Weights on Barlow GX's own scale */");
for (const token of tokens.weight.tokens) add(`weight-${token.name}`, token.value);
writeFileSync(vendor("ad-tokens.css"), `/* Generated by scripts/vendor.mjs from packages/ad-tape/src/ad-tokens.json. Do not edit by hand:\n   change the shared tokens in the package, and every tool follows. */\n:root {\n${lines.join("\n")}\n}\n`);
copyFileSync(fileURLToPath(new URL("../../../packages/ad-shell/shell.css", import.meta.url)), vendor("shell.css"));
copyFileSync(fileURLToPath(new URL("../../../packages/ad-shell/ui.css", import.meta.url)), vendor("ui.css"));
mkdirSync(`${tool}vendor/fonts`, { recursive: true });
copyFileSync(fileURLToPath(new URL("../../../packages/ad-shell/fonts/BarlowGX-SemiCondensed.ttf", import.meta.url)), vendor("fonts/BarlowGX-SemiCondensed.ttf"));
console.log("vendor/tape.js, ad-tokens.json, ad-tokens.css and shell.css written from the shared packages.");

execFileSync(fileURLToPath(new URL("../../../node_modules/.bin/esbuild", import.meta.url)), [fileURLToPath(new URL("../../../packages/ad-shell/preview.ts", import.meta.url)), "--bundle", "--format=esm", "--target=es2020", `--outfile=${vendor("preview.js")}`], { stdio: "inherit" });
copyFileSync(fileURLToPath(new URL("../../../packages/ad-shell/preview.css", import.meta.url)), vendor("preview.css"));
